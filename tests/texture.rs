//! 贴图解码单测：内联一张 86 字节的 3x2 RGBA PNG，验证行序、通道顺序与透明像素都原样保留。

use amadeus_emote_loader::decode_png;

/// 3x2，逐像素：(255,0,0,255) (0,255,0,128) (0,0,255,0) / (10,20,30,255) (40,50,60,7) (255,255,255,255)
const PNG: &[u8] = &[137, 80, 78, 71, 13, 10, 26, 10, 0, 0, 0, 13, 73, 72, 68, 82, 0, 0, 0, 3, 0, 0, 0, 2, 8, 6, 0, 0, 0, 157, 116, 102, 26, 0, 0, 0, 29, 73, 68, 65, 84, 120, 156, 99, 248, 207, 192, 240, 31, 8, 27, 64, 20, 3, 151, 136, 220, 127, 13, 35, 27, 246, 255, 64, 0, 0, 116, 94, 10, 81, 39, 65, 95, 166, 0, 0, 0, 0, 73, 69, 78, 68, 174, 66, 96, 130];

#[test]
fn 解码出紧密排列的_rgba8() {
    let texture = decode_png(PNG).expect("解码成功");
    assert_eq!((texture.width, texture.height), (3, 2));
    assert_eq!(
        texture.rgba,
        vec![
            255, 0, 0, 255, 0, 255, 0, 128, 0, 0, 255, 0,
            10, 20, 30, 255, 40, 50, 60, 7, 255, 255, 255, 255,
        ],
        "行序自上而下，alpha=0 的像素也要保留原始 RGB（浏览器 canvas 中转会把它抹成 0）"
    );
}

#[test]
fn 非_png_输入报错() {
    assert!(decode_png(b"not a png").is_err());
}
